#!/usr/bin/env bash
# MagGCS udev privilege helper (ADR-009, issues.md #42).
#
# Invoked through pkexec (the desktop app prompts for the password). The
# helper deliberately does ONE thing:
#
#   install:  read the rule text from STDIN, validate it against a strict
#             grammar, write it to /etc/udev/rules.d/99-maggcs.rules, and
#             reload + trigger the usb subsystem.
#   uninstall delete /etc/udev/rules.d/99-maggcs.rules and reload.
#
# Everything else is rejected: no paths on argv, no commands, no shell
# expansion of untrusted input. Re-running is idempotent; the uninstall is
# the recovery path (delete the file + reload).
set -euo pipefail

RULES_FILE="/etc/udev/rules.d/99-maggcs.rules"

# Strict grammar: only udev match/assignment lines for tty devices bound to
# VID/PID, comments and blanks. One rule per line, no operators beyond =, no
# shell metacharacters anywhere.
valid_rule() {
  local line="$1"
  [[ "$line" =~ ^SUBSYSTEM==\"tty\",[[:space:]]*ATTRS\{idVendor\}==\"[0-9a-fA-F]{4}\",[[:space:]]*ATTRS\{idProduct\}==\"[0-9a-fA-F]{4}\",[[:space:]]*MODE=\"0666\"[[:space:]]*$ ]]
}

mode="${1:-install}"

case "$mode" in
  install)
    rules="$(cat)"
    validated=""
    while IFS= read -r line; do
      [[ -z "$line" || "$line" == \#* ]] && continue
      if valid_rule "$line"; then
        validated+="$line"$'\n'
      else
        echo "rejected rule line: $line" >&2
        exit 1
      fi
    done <<< "$rules"

    if [[ -z "$validated" ]]; then
      echo "no valid rules on stdin" >&2
      exit 1
    fi

    {
      echo "# MagGCS udev rule — FC/RTK USB serial access (issues.md #42)"
      echo "# Generated by the MagGCS settings dialog; delete this file to undo."
      printf '%s' "$validated"
    } > "$RULES_FILE"

    udevadm control --reload
    udevadm trigger --subsystem-match=tty
    echo "installed: $RULES_FILE"
    ;;

  uninstall)
    rm -f "$RULES_FILE"
    udevadm control --reload
    echo "uninstalled: $RULES_FILE"
    ;;

  *)
    echo "usage: $0 [install|uninstall] < rules.txt" >&2
    exit 1
    ;;
esac
